CREATE TABLE cities (
    id BIGSERIAL PRIMARY KEY,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 120),
    normalized_name TEXT NOT NULL UNIQUE
);
CREATE TABLE running_clubs (
    id BIGSERIAL PRIMARY KEY,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 120),
    normalized_name TEXT NOT NULL UNIQUE
);
ALTER TABLE pacemakers DROP CONSTRAINT pacemakers_motto_check;
ALTER TABLE pacemakers
    ADD CONSTRAINT pacemakers_about_check CHECK (char_length(motto) <= 5000),
    ADD COLUMN login TEXT UNIQUE CHECK (login ~ '^[a-z][a-z0-9_-]{2,29}$'),
    ADD COLUMN city_id BIGINT REFERENCES cities(id),
    ADD COLUMN club_id BIGINT REFERENCES running_clubs(id),
    ADD COLUMN personal_records JSONB NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(personal_records) = 'object');
CREATE INDEX pacemakers_city_id_idx ON pacemakers(city_id);
CREATE INDEX pacemakers_club_id_idx ON pacemakers(club_id);
